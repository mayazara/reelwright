//! Writes the bundled `.cube` files and their attribution rows from
//! `rw_fx::grades`. Run from the repository root:
//! `cargo run -p rw-fx --example make_luts`.

use rw_fx::{LUT_SIZE, Lut, grades::GRADES};
use std::path::Path;

fn main() {
    let dir = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../assets/luts");
    std::fs::create_dir_all(&dir).expect("create assets/luts");
    for g in GRADES {
        let lut = Lut::from_fn(LUT_SIZE, g.apply);
        let text = lut.to_cube(
            g.name,
            &[
                "Original look created for this project.",
                "Licence: MIT OR Apache-2.0. Generated by rw-fx/examples/make_luts.rs.",
            ],
        );
        std::fs::write(dir.join(format!("{}.cube", g.id)), text).expect("write LUT");
        println!(
            "| `luts/{}.cube` | original | MIT OR Apache-2.0 | Reelwright contributors |",
            g.id
        );
    }
}
